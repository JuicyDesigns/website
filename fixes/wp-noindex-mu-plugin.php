function jd_recovery_current_path() {
    $p = strtok($_SERVER['REQUEST_URI'] ?? '/', '?');
    if (substr($p, -1) !== '/') { $p .= '/'; }
    return $p;
}

// HTTP header (covers non-HTML fetches and is the strongest signal)
add_action('send_headers', function () {
    if (isset(jd_recovery_noindex_paths()[jd_recovery_current_path()])) {
        header('X-Robots-Tag: noindex, follow', true);
    }
});

// Meta tag as belt-and-braces; also override Yoast/RankMath output if present
add_action('wp_head', function () {
    if (isset(jd_recovery_noindex_paths()[jd_recovery_current_path()])) {
        echo '<meta name="robots" content="noindex, follow" />' . PHP_EOL;
    }
}, 0);
add_filter('wpseo_robots', function ($robots) {
    return isset(jd_recovery_noindex_paths()[jd_recovery_current_path()]) ? 'noindex, follow' : $robots;
});
add_filter('rank_math/frontend/robots', function ($robots) {
    if (isset(jd_recovery_noindex_paths()[jd_recovery_current_path()])) {
        $robots['index'] = 'noindex';
    }
    return $robots;
});
